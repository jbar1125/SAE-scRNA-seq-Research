#!/usr/bin/env python3
"""Archive/push the completed bounded NMF sensitivity after real-artifact checks."""
import argparse
import csv
from datetime import datetime, timezone
import gzip
import json
from pathlib import Path
import time

import numpy as np

from archive_norman_cpu_results import copy_exclusive, publish, sha
from norman_nmf_convergence import ARMS, NEW_ARM, joint_followup

ROOT = Path(__file__).resolve().parents[1]
RUN = Path('/workspace/research-runs/norman-nmf-convergence-v1')
DEST = ROOT / 'data_norman_continuation/nmf_convergence'


def collect(publish_git=False):
    source = RUN / 'results.json'
    log = RUN.with_suffix('.log')
    if not source.exists() or not log.exists() or '"stage": "complete"' not in log.read_text():
        return False
    r = json.loads(source.read_text())
    if (r['association_family_size'], r['identity_family_size']) != (6615, 63):
        raise ValueError('complete seven-fit families required')
    fit = r['fit']
    if not 1 <= fit['iterations'] <= 800 or fit['settings']['init'] != 'custom' or fit['settings']['tol'] != .0001:
        raise ValueError('declared bounded solver settings differ')
    for name, expected in r['provenance']['source_sha256'].items():
        if sha(ROOT / name) != expected:
            raise ValueError(f'source/input archive changed: {name}')
    for kind in ['model', 'scores']:
        if sha(r['provenance']['new_' + kind + '_path']) != r['provenance']['new_' + kind + '_sha256']:
            raise ValueError('actual fitted artifact SHA differs')
    scores = np.load(r['provenance']['new_scores_path'], mmap_mode='r', allow_pickle=False)
    h = np.load(r['provenance']['new_model_path'], allow_pickle=False)['components']
    if scores.shape != (111445, 64) or h.shape != (64, 4081) or np.any(h < 0) or not np.isfinite(h).all():
        raise ValueError('fitted factor dimensions or values differ')
    for start in range(0, len(scores), 4096):
        if not np.isfinite(scores[start:start + 4096]).all() or np.any(scores[start:start + 4096] < 0):
            raise ValueError('nonfinite or negative actual factors')
    original = {arm: r['representations'][arm] for arm in ARMS}
    combined, a, i = joint_followup(original, r['representations'][NEW_ARM])
    if combined != r['representations'] or (a, i) != (6615, 63):
        raise ValueError('joint BH/Holm records do not reproduce')
    with (RUN / 'comparisons.csv').open() as stream:
        rows = list(csv.DictReader(stream))
    if len(rows) != 6615 or len({(x['arm'], x['program'], x['pert']) for x in rows}) != 6615:
        raise ValueError('comparison CSV is incomplete or duplicated')
    new = r['representations'][NEW_ARM]
    identity = new['identity_heterogeneity']
    if identity['n_permutations_requested'] != 9999:
        raise ValueError('permutation plan differs')
    if any(x['matched'] for x in identity['programs'].values()) and identity['n_permutations'] != 9999:
        raise ValueError('declared permutations did not finish')
    DEST.mkdir(parents=True, exist_ok=True)
    compressed = DEST / 'results.json.gz'
    payload = source.read_bytes()
    if compressed.exists():
        if gzip.decompress(compressed.read_bytes()) != payload:
            raise ValueError('existing archive differs; preserving it')
    else:
        with compressed.open('xb') as raw:
            with gzip.GzipFile(fileobj=raw, mode='wb', mtime=0) as stream:
                stream.write(payload)
    for src, dst in [(RUN / 'comparisons.csv', DEST / 'comparisons.csv'), (log, DEST / 'run.log')]:
        if dst.exists():
            if sha(src) != sha(dst):
                raise ValueError('existing archived CSV/log differs')
        else:
            copy_exclusive(src, dst)
    summary_path = DEST / 'summary.json'
    summary = {'fit': fit, 'programs': r['summary'],
               'scope': r['scope'], 'raw_result_sha256': sha(source)}
    text = json.dumps(summary, indent=2) + '\n'
    if summary_path.exists() and summary_path.read_text() != text:
        raise ValueError('existing summary differs')
    if not summary_path.exists():
        summary_path.write_text(text)
    validation = DEST / 'validation.json'
    if not validation.exists():
        validation.write_text(json.dumps({'status': 'PASS', 'checked_utc': datetime.now(timezone.utc).isoformat(),
            'association_family': a, 'identity_family': i, 'unique_csv_records': len(rows),
            'actual_factor_hashes_and_values_checked': True, 'joint_corrections_reproduced': True,
            'raw_result_sha256': sha(source), 'compressed_result_sha256': sha(compressed),
            'generator_sha256': sha(Path(__file__))}, indent=2) + '\n')
    report = ROOT / 'docs/NORMAN_NMF_CONVERGENCE.md'
    marker = '<!-- Generated by archive_norman_nmf_followup.py. -->'
    lines = [marker, '# Bounded NMF warm-restart sensitivity', '',
        f"The additional fit executed {fit['iterations']} iterations; absence of a convergence warning: **{fit['convergence_warning_absent']}**.",
        f"Frobenius reconstruction error: {fit['original_capped_error']:.6f} before, {fit['reconstruction_frobenius_error']:.6f} after.",
        f"Actual fit time: {fit['fit_elapsed_seconds']:.1f} seconds on four CPU threads.", '',
        'This is custom initialization from the original factors with a reset stopping reference, not uninterrupted continuation. Numerical stopping does not prove a global optimum or biological fidelity. The original capped fit and six-arm results remain preserved.', '',
        '| Panel | SAE 0 | SAE 1 | SAE 2 | Control SAE | PCA | Capped NMF | Warm NMF |',
        '|---|---:|---:|---:|---:|---:|---:|---:|']
    for name, programs in r['summary'].items():
        values = [str(programs[arm]['n_associations']) if programs[arm]['matched'] else 'Unscored' for arm in ARMS + [NEW_ARM]]
        lines.append('| ' + name + ' | ' + ' | '.join(values) + ' |')
    lines.extend(['', 'All 6,615 association hypotheses enter joint BH and all 63 identity hypotheses enter Holm. Unmatched p=1 records remain. Complete outputs, all comparisons, solver warnings and actual model/score/source hashes were checked and archived in [the evidence directory](../data_norman_continuation/nmf_convergence/summary.json).', '', r['scope'], ''])
    report_text = '\n'.join(lines)
    if report.exists() and not report.read_text().startswith(marker):
        raise ValueError('existing report is not generator-owned')
    report.write_text(report_text)
    paths = [compressed, DEST / 'comparisons.csv', DEST / 'run.log', summary_path, validation, report]
    if publish_git:
        publish(paths)
    print(json.dumps({'archive_status': 'PASS', 'published_requested': publish_git, 'fit_iterations': fit['iterations'],
                      'convergence_warning_absent': fit['convergence_warning_absent']}), flush=True)
    return True


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--watch', action='store_true')
    parser.add_argument('--publish', action='store_true')
    args = parser.parse_args()
    while True:
        done = collect(args.publish)
        if done or not args.watch:
            break
        time.sleep(30)
